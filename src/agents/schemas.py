"""Pydantic Schemas for Structured Agentic AI Decisions."""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class MarketRegime(str, Enum):
  BULLISH_TREND = "BULLISH_TREND"
  BEARISH_TREND = "BEARISH_TREND"
  CALM_RANGE = "CALM_RANGE"
  VOLATILE_PANIC = "VOLATILE_PANIC"


class ActionType(str, Enum):
  BUY = "BUY"
  SELL = "SELL"
  HOLD = "HOLD"


class MarketFeaturesInput(BaseModel):
  symbol: str
  price_toman: float
  ema_spread_pct: float
  rsi_14: float
  atr_pct: float
  vol_ratio: float
  spread_pct: float
  trend_direction: str


class RegimeAnalysisOutput(BaseModel):
  """Strict structured output produced by the Market Regime Agent."""

  symbol: str
  regime: MarketRegime
  confidence: float = Field(
      ge=0.0,
      le=1.0,
      description="Confidence score of the regime classification",
  )
  volatility_state: str = Field(
      description="Description of current volatility (e.g. LOW, NORMAL, HIGH, EXTREME)"
  )
  recommended_action: ActionType = Field(
      description="High-level action recommendation"
  )
  max_suggested_allocation_pct: float = Field(
      default=10.0,
      ge=0.0,
      le=10.0,
      description="Maximum portfolio percentage to allocate (capped at 10%)",
  )
  reasoning: str = Field(
      description="Detailed technical reasoning for the classification"
  )


class ProposedTradeSignal(BaseModel):
  """Proposed trade signal generated by Strategy Engine before Risk Engine validation."""

  symbol: str
  action: ActionType
  target_price_toman: float
  order_value_toman: float
  regime: MarketRegime
  ai_confidence: float
  stop_loss_toman: Optional[float] = None
  take_profit_toman: Optional[float] = None
  rationale: str
  timestamp: str
